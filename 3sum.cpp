// Given an integer array nums, return all the triplets [nums[i], nums[j], nums[k]] 
// such that i != j, i != k, and j != k, and nums[i] + nums[j] + nums[k] == 0.

// INPUT : nums = [-1,0,1,2,-1,-4]
// OUTPUT : [[-1,-1,2],[-1,0,1]]

class Solution {
public:
    vector<vector<int>> threeSum(vector<int>& nums) {
        std::vector<std::vector<int>> result;          // Вектор для хранения найденных троек, сумма которых равна 0
        std::sort(nums.begin(), nums.end());           // Сортируем массив по возрастанию — это нужно для двух указателей и пропуска дубликатов

        for (int i = 0; i < nums.size(); i++){         // Перебираем первый элемент тройки (индекс i)
            if (i > 0 && nums[i] == nums[i - 1]){      // Если текущий элемент равен предыдущему, пропускаем его, чтобы не получить одинаковые тройки
                continue;                              // Переходим к следующей итерации цикла
            }

            int j = i + 1;                             // Левый указатель: начинает сразу после i
            int k = nums.size() - 1;                   // Правый указатель: начинает с конца массива

            while (j < k){                             // Пока указатели не встретились, ищем пару для nums[i]
                int total = nums[i] + nums[j] + nums[k]; // Считаем сумму текущей тройки
                if (total > 0){                        // Если сумма больше нуля, нужно уменьшить её — сдвигаем правый указатель влево
                    k -= 1;
                } else if (total < 0){                 // Если сумма меньше нуля, нужно увеличить её — сдвигаем левый указатель вправо
                    j += 1;
                } else {                               // Если сумма равна нулю — нашли подходящую тройку
                    result.push_back({nums[i], nums[j], nums[k]});
                    j += 1;                            // Сдвигаем левый указатель, чтобы искать следующую пару
                    while (nums[j] == nums[j - 1] && j < k){ // Пропускаем одинаковые значения j, чтобы избежать дубликатов троек
                        j += 1;                        // Увеличиваем j, пока не найдём новое значение или пока j < k
                    }
                }
            }
        }
        return result;
    }
};